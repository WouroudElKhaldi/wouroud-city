import type { FloorKind, SurfaceSpec, WallKind } from "@/components/city/skillhouse/finishKit";
import type { Cut, CutOptions } from "./plan";

/**
 * Every skill's building, designed from what the skill is: its colors, its character, what it's used
 * for. Each has its own floor plan (cut + options + size), its own finishes and lights, a centerpiece in
 * the main hall, and rooms around it. `hero` and rooms of kind "signature" name pieces built only for
 * that skill (see components/city/skillhouse/signatures); the other room kinds are shared modules
 * dressed with the skill's palette and words.
 */

export type LightKind = "pendant" | "neon" | "industrial" | "panel" | "track" | "lantern" | "bulbs" | "chandelier";

export type ModuleKind =
  | "terminal"
  | "lounge"
  | "library"
  | "gallery"
  | "workshop"
  | "classroom"
  | "meeting"
  | "lab"
  | "servers"
  | "showcase"
  | "timeline"
  | "cafe"
  | "garden"
  | "stage"
  | "meter"
  | "quiz"
  | "demo"
  | "signature";

export type RoomSpec = {
  kind: ModuleKind;
  label: string;
  /** For "signature": which piece */
  sig?: string;
  /** Own floor for this room */
  floor?: SurfaceSpec<FloorKind>;
  /** Lines used by boards, posters, whiteboards and talks */
  notes?: string[];
  /** Style hint for shared modules (e.g. a lounge of beanbags, cushions or leather) */
  look?: string;
};

export type QuizQuestion = { q: string; a: string[]; ok: number };

export type HouseDef = {
  /** One line about the idea of the building, shown in the lobby */
  concept: string;
  size: [number, number, number];
  cut: Cut;
  options?: CutOptions;
  floor: SurfaceSpec<FloorKind>;
  wall: SurfaceSpec<WallKind>;
  /** Interior walls (defaults to the outer wall look) */
  inner?: SurfaceSpec<WallKind>;
  /** Baseboards, door frames, railings */
  trim: string;
  ceiling: string;
  lights: LightKind;
  lightColor: string;
  /** main, second, ink (text on light), paper (light surfaces) */
  palette: [string, string, string, string];
  hero: string;
  rooms: RoomSpec[];
  quiz: QuizQuestion[];
};

const F = <K extends FloorKind | WallKind>(kind: K, ...colors: string[]): SurfaceSpec<K> => ({ kind, colors });

